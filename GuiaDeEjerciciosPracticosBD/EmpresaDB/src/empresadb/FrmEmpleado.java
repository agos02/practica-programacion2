    private void cargarDepartamentos() {

    comboDepto.removeAllItems();

    try (
        Connection conn = ConexionDB.conectar();
        PreparedStatement ps = conn.prepareStatement("SELECT * FROM departamentos");
        ResultSet rs = ps.executeQuery()
    ) {

        while (rs.next()) {
            comboDepto.addItem(
                rs.getInt("id_depto") + " - " + rs.getString("nombre_depto")
            );
        }

    } catch (Exception e) {
        System.out.println("Error: " + e.getMessage());
    }
}
    
    
    public void cargarTabla() {

    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tablaEmpleados.getModel();

        modelo.setRowCount(0);

        EmpleadoDAO dao = new EmpleadoDAO();

    for (Empleado emp : dao.consultarTodos()) {

        Object[] fila = {
            emp.getId(),
            emp.getNombre(),
            emp.getDepartamento()
        };

        modelo.addRow(fila);
    }
}
    


    
    
    
