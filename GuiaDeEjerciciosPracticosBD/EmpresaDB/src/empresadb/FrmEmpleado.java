    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
     
    String seleccionado = (String) comboDepto.getSelectedItem();
    int idDepto = Integer.parseInt(seleccionado.split(" - ")[0]);

    Empleado emp = new Empleado();
    emp.setNombre(jTextField2.getText());       // Nombre del empleado
    emp.setIdDepto(idDepto);                    // ID del departamento
    emp.setFoto(jTextFieldFoto.getText());      // Ruta de la foto seleccionada

    EmpleadoDAO dao = new EmpleadoDAO();
    dao.insertar(emp);

    cargarTabla();
    }//GEN-LAST:event_jButton1ActionPerformed

    private void btnBuscarFotoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarFotoActionPerformed

     javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
    int result = fileChooser.showOpenDialog(this);

    if (result == javax.swing.JFileChooser.APPROVE_OPTION) {
        java.io.File archivo = fileChooser.getSelectedFile();
        String ruta = archivo.getAbsolutePath();

        // Mostrar la foto en el JLabel
        javax.swing.ImageIcon icon = new javax.swing.ImageIcon(ruta);
        lblFoto.setIcon(icon);

        // Guardar la ruta en el campo oculto
        jTextFieldFoto.setText(ruta);
    }
    }//GEN-LAST:event_btnBuscarFotoActionPerformed

